"""Inventory the third-party Rust licenses of the packaged native extension.

Objective:
- Generate and verify the notice file that must accompany binary wheels, so every crate
  linked into the extension ships with its license text.

Technical approach:
- Ask `cargo metadata --locked` for the resolved normal-dependency graph of `rko-py`.
- For each registry crate, record name, version, SPDX expression and the verbatim license
  files found in its source directory, in a deterministic order.

Flow (pseudocode):
1. Resolve the dependency graph from the committed `Cargo.lock`.
2. Render one block per crate: header, license expression, then each license file.
3. Write the file, or compare with the committed one in `--check` mode.

Important criteria:
- The output depends only on `Cargo.lock` and the crates' sources, never on timestamps.
- A crate without a license file or SPDX expression is a hard error, not a silent gap.
- This inventories notices; it does not certify the combined licensing, which `NOTICE`
  leaves to the owner.

Inputs/Outputs:
- Input: repository `Cargo.toml`/`Cargo.lock` and the local cargo registry.
- Output: `engines/THIRD_PARTY_LICENSES.txt`, or a nonzero exit when it is stale.
"""

import argparse
import json
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "engines" / "THIRD_PARTY_LICENSES.txt"
SEPARATOR = "=" * 78


class ThirdPartyLicenses:
    """Render the third-party license inventory of the native extension.

    Responsibilities:
    - Resolve the locked normal-dependency closure of the extension crate.
    - Concatenate crate headers and verbatim license files deterministically.

    Attributes:
        root (Path): Repository root containing the cargo workspace.
        package (str): Workspace package whose dependency closure is inventoried.
    """

    def __init__(self, root: Path = ROOT, package: str = "rko-py") -> None:
        """Store the workspace location and target package.

        Args:
            root (Path): Repository root containing the cargo workspace.
            package (str): Workspace package whose closure is inventoried.
        """
        self.root = root
        self.package = package

    def render(self) -> str:
        """Build the inventory text from the locked dependency graph.

        Returns:
            str: Deterministic notice file contents.

        Raises:
            RuntimeError: If cargo fails or a crate lacks a license expression or file.
        """
        process = subprocess.run(
            [
                "cargo",
                "metadata",
                "--format-version",
                "1",
                "--locked",
                "--filter-platform",
                "x86_64-unknown-linux-gnu",
            ],
            cwd=self.root,
            capture_output=True,
            text=True,
            check=False,
        )
        if process.returncode != 0:
            raise RuntimeError(f"cargo metadata failed: {process.stderr[-1000:]}")
        metadata = json.loads(process.stdout)
        packages = {item["id"]: item for item in metadata["packages"]}
        nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
        start = next(item["id"] for item in metadata["packages"] if item["name"] == self.package)
        seen: set[str] = set()
        pending = [start]
        while pending:
            current = pending.pop()
            if current in seen:
                continue
            seen.add(current)
            for dependency in nodes[current]["deps"]:
                if any(kind["kind"] in (None, "normal") for kind in dependency["dep_kinds"]):
                    pending.append(dependency["pkg"])
        blocks = [
            "Third-party Rust crates linked into the native extension.\n"
            "Generated by tools/third_party_licenses.py from Cargo.lock; do not edit."
        ]
        for identifier in sorted(
            seen, key=lambda key: (packages[key]["name"], packages[key]["version"])
        ):
            item = packages[identifier]
            if item.get("source") is None:
                continue
            expression = item.get("license")
            if not expression:
                raise RuntimeError(f"{item['name']} declares no SPDX license expression")
            directory = Path(item["manifest_path"]).parent
            files = sorted(
                path
                for path in directory.iterdir()
                if path.is_file()
                and path.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "UNLICENSE"))
            )
            if not files:
                raise RuntimeError(f"{item['name']} {item['version']} ships no license file")
            parts = [f"{SEPARATOR}\n{item['name']} {item['version']}\nLicense: {expression}"]
            for path in files:
                parts.append(f"--- {path.name} ---\n{path.read_text(encoding='utf-8').strip()}")
            blocks.append("\n\n".join(parts))
        return "\n\n".join(blocks) + "\n"

    def run(self, check: bool) -> int:
        """Write the inventory, or verify the committed one is current.

        Args:
            check (bool): Compare instead of writing.

        Returns:
            int: Zero on success, one when `check` finds a stale file.

        Raises:
            RuntimeError: If the inventory cannot be rendered.
        """
        text = self.render()
        if check:
            if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
                print(
                    f"{OUTPUT.relative_to(self.root)} is stale; run tools/third_party_licenses.py"
                )
                return 1
            return 0
        OUTPUT.write_text(text, encoding="utf-8")
        return 0


def main(argv: Sequence[str] | None = None) -> int:
    """Run the command-line entry point.

    Args:
        argv (Sequence[str] | None): Optional arguments; `--check` verifies only.

    Returns:
        int: Process exit status.

    Raises:
        RuntimeError: If the inventory cannot be rendered.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)
    return ThirdPartyLicenses().run(arguments.check)


if __name__ == "__main__":
    sys.exit(main())
